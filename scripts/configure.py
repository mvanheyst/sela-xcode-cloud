#!/usr/bin/env python3
"""Configure an Apple team, app ID, build number, and optional default study server."""
import argparse
import plistlib
import re
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--team-id', required=True)
    parser.add_argument('--bundle-id', required=True)
    parser.add_argument('--api-url', default='')
    parser.add_argument('--version', default='1.0.0')
    parser.add_argument('--build', default='1')
    args = parser.parse_args()
    if not re.fullmatch(r'[A-Z0-9]{10}', args.team_id):
        parser.error('Apple Team ID must contain 10 uppercase letters/numbers.')
    if not re.fullmatch(r'[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+){2,}', args.bundle_id) or args.bundle_id.startswith(('com.example.', 'com.yourcompany.')):
        parser.error('Use your own reverse-domain bundle ID, for example ca.yourdomain.sela.')
    if not re.fullmatch(r'\d{1,4}\.\d{1,2}\.\d{1,2}', args.version):
        parser.error('Version must have three numeric components, such as 1.0.0.')
    if not re.fullmatch(r'[1-9]\d{0,3}(?:\.\d{1,2}){0,2}', args.build):
        parser.error('Build must be a positive number (1–9999), optionally with two numeric components.')
    api = args.api_url.strip().rstrip('/')
    if api:
        parts = urlsplit(api)
        if parts.scheme != 'https' or not parts.hostname or parts.username or parts.password or parts.path or parts.query or parts.fragment:
            parser.error('API URL must be an HTTPS origin without a path, credentials, query, or fragment.')
        try:
            parts.port
        except ValueError:
            parser.error('API URL has an invalid port.')
    config = ROOT / 'ios/BuildSettings.xcconfig'
    config.write_text('// Generated by scripts/configure.py. Contains no private keys.\n'
        f'DEVELOPMENT_TEAM = {args.team_id}\nPRODUCT_BUNDLE_IDENTIFIER = {args.bundle_id}\n'
        f'MARKETING_VERSION = {args.version}\nCURRENT_PROJECT_VERSION = {args.build}\nSELA_TEST_BUNDLE_ID = {args.bundle_id}.tests\nVERSIONING_SYSTEM = apple-generic\nCODE_SIGN_STYLE = Automatic\n')
    info = ROOT / 'ios/SELA/Info.plist'
    data = plistlib.loads(info.read_bytes())
    data['SELAAPIBaseURL'] = api
    info.write_bytes(plistlib.dumps(data, sort_keys=False))
    print('SELA configured. Commit the changes to your repository, then connect the shared SELA scheme to Xcode Cloud.')

if __name__ == '__main__':
    main()
